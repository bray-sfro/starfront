using System.Text.Json;
using System.Text.Json.Serialization;

namespace RapidStackerCollab.Core.Api;

/// <summary>
/// The one set of JSON options for the contract: snake_case names, nulls omitted on write, unknown members
/// ignored on read (the contract says readers must ignore unknown fields).
/// </summary>
public static class ApiJson
{
    public static JsonSerializerOptions Options { get; } = Create();

    private static JsonSerializerOptions Create()
    {
        var o = new JsonSerializerOptions
        {
            PropertyNamingPolicy = JsonNamingPolicy.SnakeCaseLower,
            DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
            PropertyNameCaseInsensitive = false,
            NumberHandling = JsonNumberHandling.AllowReadingFromString,
            WriteIndented = false,
        };
        return o;
    }

    public static string Serialize<T>(T value) => JsonSerializer.Serialize(value, Options);

    public static T? Deserialize<T>(string json) => JsonSerializer.Deserialize<T>(json, Options);
}
